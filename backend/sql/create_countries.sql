-- ISO 3166-1 reference table.
--
-- Holds the canonical alpha-2 / alpha-3 / numeric codes plus the country name
-- and its flag emoji, so the dashboard can resolve `horses.country` (which
-- stores the alpha-2 code) to a display name and a flag without round-tripping
-- to a third-party service.
--
-- Source: ISO 3166-1 (current list of officially-assigned codes).
-- Apply once; re-running is safe (uses ON CONFLICT DO NOTHING on alpha-2).

