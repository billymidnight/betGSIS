    alpha2     CHAR(2)  PRIMARY KEY,
    alpha3     CHAR(3)  NOT NULL UNIQUE,
    numeric3   CHAR(3)  NOT NULL,
    name       TEXT     NOT NULL,
    flag_emoji TEXT     NOT NULL
);

CREATE INDEX IF NOT EXISTS countries_name_idx ON countries (name);


